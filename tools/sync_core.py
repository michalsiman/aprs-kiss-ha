#!/usr/bin/env python3
"""Copy the shared core from the standalone app (aprs-kiss-app) into the integration.

The integration and the app run the same engine: APRS, APRS-IS, iGate, digipeater, BBS SERVER, TAK,
GPS, #APRSThursday, offline maps. It lives in the app's repository (src/aprs_kiss_core) and is copied
here unchanged into custom_components/aprs_kiss/core; never edit the copy, change the app and run:

    python3 tools/sync_core.py [path/to/aprs-kiss-app]
"""

from __future__ import annotations

import json
import runpy
import shutil
import sys
from pathlib import Path

HERE = Path(__file__).resolve().parents[1]
TARGET = HERE / "custom_components" / "aprs_kiss" / "core"
FRONTEND = HERE / "custom_components" / "aprs_kiss" / "frontend"
SKIP = {"android_bt.py", "android_usb.py", "ble.py", "__pycache__"}  # phones and the app's Flet extension only


def main() -> None:
    app = Path(sys.argv[1]) if len(sys.argv) > 1 else HERE.parent / "aprs-kiss-app"
    source = app / "src" / "aprs_kiss_core"
    if not (source / "engine.py").exists():
        sys.exit(f"Not the app's core: {source}")
    if TARGET.exists():
        shutil.rmtree(TARGET)
    shutil.copytree(source, TARGET, ignore=lambda _d, names: [n for n in names if n in SKIP])
    (TARGET / "SYNCED_FROM.txt").write_text(
        "Copied from aprs-kiss-app/src/aprs_kiss_core by tools/sync_core.py. Do not edit here.\n")
    print(f"core copied: {sum(1 for _ in TARGET.rglob('*.py'))} files")
    # the panel's map: the APRS symbols with their emoji and names, and the bundled offline map
    ui = app / "src" / "aprs_kiss_app"
    sym = runpy.run_path(str(ui / "symbols.py"))
    table = {code: [e, en, cs] for code, (e, en, cs) in sym["ALL"].items()}
    common = [list(s) for s in sym["SYMBOLS"]]
    (FRONTEND / "symbols.js").write_text(
        "// Generated by tools/sync_core.py from the app's symbols.py. Do not edit.\n"
        f"export const ALL = {json.dumps(table, ensure_ascii=False)};\n"
        f"export const COMMON = {json.dumps(common, ensure_ascii=False)};\n"
        f"export const UNKNOWN = {json.dumps(sym['UNKNOWN'], ensure_ascii=False)};\n", encoding="utf-8")
    shutil.copy2(ui / "offline" / "world.json", FRONTEND / "world.json")
    print("frontend: symbols.js, world.json")


if __name__ == "__main__":
    main()
